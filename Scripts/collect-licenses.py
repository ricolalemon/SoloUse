#!/usr/bin/env python3
"""Collect locked Cargo license evidence. Run after dependency changes; review warnings."""
import argparse, hashlib, json, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--metadata', type=Path, help='Use an existing full cargo metadata JSON (private paths are not copied)')
    parser.add_argument('--ios-metadata', type=Path)
    args = parser.parse_args()
    def metadata(platform=None):
        cmd=['cargo','metadata','--manifest-path',str(ROOT/'Native/Cargo.toml'),'--locked','--format-version','1']
        if platform: cmd += ['--filter-platform',platform]
        return json.loads(subprocess.check_output(cmd))
    full=json.loads(args.metadata.read_text()) if args.metadata else metadata()
    ios=json.loads(args.ios_metadata.read_text()) if args.ios_metadata else metadata('aarch64-apple-ios')
    ios_ids={n['id'] for n in ios['resolve']['nodes']}
    output=ROOT/'Licenses/Cargo'; output.mkdir(parents=True,exist_ok=True)
    rows=[]; warnings=[]
    canonical=(ROOT/'LICENSE').read_text().split('Permission is hereby granted',1)[1]
    canonical='Permission is hereby granted'+canonical
    for p in sorted(full['packages'],key=lambda p:(p['name'],p['version'])):
        if p['id']==full['resolve']['root']: continue
        source=Path(p['manifest_path']).parent
        dest=output/(p['name']+'-'+p['version']);dest.mkdir(exist_ok=True)
        def is_notice(q):
            name=q.name.upper()
            return any(k in name for k in ['LICENSE','LICENCE','COPYING','COPYRIGHT','NOTICE']) or name in ['AUTHORS','AUTHORS.md']
        notices=[q for q in source.rglob('*') if q.is_file() and is_notice(q) and not {'target','.git'} & set(q.relative_to(source).parts)]
        records=[]
        for q in sorted(notices):
            rel=q.relative_to(source);target=dest/rel;target.parent.mkdir(parents=True,exist_ok=True)
            data=q.read_bytes();target.write_bytes(data)
            records.append({'path':str(target.relative_to(ROOT)),'sha256':hashlib.sha256(data).hexdigest()})
        spdx=p.get('license') or ''
        if not spdx: raise RuntimeError('Missing license declaration: '+p['name'])
        selected='MIT' if 'MIT' in spdx.split(' OR ') or spdx in ['MIT/Apache-2.0','Unlicense OR MIT','MIT OR Apache-2.0 OR LGPL-2.1-or-later'] else spdx
        if 'Unicode-3.0' in spdx:selected='MIT AND Unicode-3.0'
        if spdx=='Apache-2.0 AND ISC':selected=spdx
        reviewed={'MIT','Apache-2.0','BSD-3-Clause','ISC','Zlib','Apache-2.0 AND ISC','MIT AND Unicode-3.0'}
        if selected not in reviewed:raise RuntimeError('License expression requires manual review: '+p['name']+' '+spdx)
        vcs=source/'.cargo_vcs_info.json';commit=None
        if vcs.exists():commit=json.loads(vcs.read_text()).get('git',{}).get('sha1')
        note=None
        if not notices:
            if p['name'] not in ['ns-keyed-archive','plist-macro'] or 'MIT' not in spdx:
                raise RuntimeError('No license evidence file: '+p['name'])
            note='Upstream crate declares this SPDX license but ships no standalone license text. Cargo.toml.orig is retained as declaration evidence; canonical MIT text is supplied separately, not represented as an upstream file.'
            warnings.append({'package':p['name'],'version':p['version'],'note':note})
            source_manifest=source/'Cargo.toml.orig'
            (dest/'UPSTREAM-MANIFEST.toml').write_bytes(source_manifest.read_bytes())
            (dest/'MIT-TEXT.txt').write_text('MIT license text for the option declared by this crate.\nAuthorship credited in upstream metadata: '+', '.join(p['authors'])+'\nNo missing copyright year is inferred.\n\n'+canonical)
            for q in [dest/'UPSTREAM-MANIFEST.toml',dest/'MIT-TEXT.txt']:
                records.append({'path':str(q.relative_to(ROOT)),'sha256':hashlib.sha256(q.read_bytes()).hexdigest()})
        row={'name':p['name'],'version':p['version'],'declared_license':spdx,'selected_option':selected,
             'repository':p.get('repository'),'authors':p.get('authors',[]),'upstream_revision':commit,
             'in_ios_resolved_graph':p['id'] in ios_ids,'notices':records}
        if note:row['note']=note
        rows.append(row)
    # No machine paths, credential files or registry source files are copied.
    report={'scope':'Cargo.lock, all resolved platforms; metadata declarations plus original notice files. Not a legal opinion. Recheck after dependency/feature changes.',
            'packages':rows,'warnings':warnings}
    (ROOT/'Licenses/cargo-inventory.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    lines=['# Locked Rust dependencies','', 'Generated by `Scripts/collect-licenses.py`. Original upstream notices are in [Cargo](Cargo/).',
           'The iOS column records membership in the resolved `aarch64-apple-ios` graph, including build dependencies; it is not a statement that every crate is linked into the final binary.','',
           '| Package | Version | Declared license | Option recorded for this distribution | iOS graph |','| --- | --- | --- | --- | --- |']
    for x in rows:lines.append(f"| {x['name']} | {x['version']} | {x['declared_license']} | {x['selected_option']} | {'yes' if x['in_ios_resolved_graph'] else 'no'} |")
    lines += ['', '## Declaration-only upstream packages','']
    for x in warnings:lines.append(f"- `{x['package']} {x['version']}`: {x['note']}")
    (ROOT/'Licenses/CARGO_DEPENDENCIES.md').write_text('\n'.join(lines)+'\n')
    print(json.dumps({'third_party_packages':len(rows),'ios_graph_packages':sum(x['in_ios_resolved_graph'] for x in rows),'declaration_only_packages':[x['package'] for x in warnings]}))
if __name__=='__main__':main()
